// js/partMesh.js: builds the plane model from a blueprint (pure geometry, zero art assets)
// The hangar and flight share this one function: what you build is what you fly.
// Geometries and materials are cached per type. The hangar rebuilds on every edit, so without caching it would leak GPU memory.

import * as THREE from 'three';
import { CELL, PARTS, cellKey } from './parts.js';
import { computeStruts } from './struts.js';

const S = CELL * 0.92;             // blocks are slightly smaller than a cell, leaving a small gap so you can see the individual pieces
const geoCache = new Map();
const matCache = new Map();

function geo(key, make) {
  if (!geoCache.has(key)) geoCache.set(key, make());
  return geoCache.get(key);
}
function mat(color, basic = false) {
  const k = color + (basic ? 'b' : 'l');
  if (!matCache.has(k)) {
    matCache.set(k, basic
      ? new THREE.MeshBasicMaterial({ color })
      : new THREE.MeshLambertMaterial({ color }));
  }
  return matCache.get(k);
}
// cylinder along the z axis (three.js defaults to y)
const zCyl = (rt, rb, h, seg = 12) => {
  const g = new THREE.CylinderGeometry(rt, rb, h, seg);
  g.rotateX(Math.PI / 2);
  return g;
};

/* A single part. Returns { group, spinner }; spinner is the propeller blade group to rotate (null if none) */
export function buildPart(type) {
  const d = PARTS[type];
  const g = new THREE.Group();
  let spinner = null;

  switch (type) {
    case 'core': {
      g.add(new THREE.Mesh(geo('box', () => new THREE.BoxGeometry(S, S, S)), mat(d.color)));
      const canopy = new THREE.Mesh(geo('canopy', () => new THREE.SphereGeometry(S * 0.34, 12, 8)), mat(0x0d1b2a));
      canopy.position.set(0, S * 0.5, -S * 0.1);
      canopy.scale.set(1, 0.7, 1.4);
      g.add(canopy);
      break;
    }
    case 'structure':
      g.add(new THREE.Mesh(geo('box', () => new THREE.BoxGeometry(S, S, S)), mat(d.color)));
      break;
    case 'armor': {
      g.add(new THREE.Mesh(geo('armorBox', () => new THREE.BoxGeometry(S * 1.04, S * 1.04, S * 1.04)), mat(d.color)));
      // two reinforcing ribs so armor reads as armor, not plain frame
      const rib = geo('rib', () => new THREE.BoxGeometry(S * 1.1, S * 0.16, S * 0.16));
      for (const y of [-0.28, 0.28]) {
        const r = new THREE.Mesh(rib, mat(0x3a414d));
        r.position.set(0, S * y, -S * 0.53);
        g.add(r);
      }
      break;
    }
    case 'wing':
      // thin plate filling the whole cell so neighboring wing pieces join into one wing
      g.add(new THREE.Mesh(geo('wing', () => new THREE.BoxGeometry(CELL, S * 0.18, CELL * 0.9)), mat(d.color)));
      break;
    case 'prop': {
      g.add(new THREE.Mesh(geo('propHub', () => zCyl(S * 0.3, S * 0.4, S * 0.9)), mat(d.color)));
      const cone = new THREE.Mesh(geo('spinnerCone', () => {
        const c = new THREE.ConeGeometry(S * 0.3, S * 0.45, 12);
        c.rotateX(-Math.PI / 2);        // pointed end toward -z (the nose)
        return c;
      }), mat(0xe8e2d0));
      cone.position.z = -S * 0.62;
      g.add(cone);
      spinner = new THREE.Group();
      spinner.position.z = -S * 0.55;
      const blade = geo('blade', () => new THREE.BoxGeometry(S * 0.16, S * 1.9, S * 0.08));
      for (const rz of [0, Math.PI / 2]) {
        const b = new THREE.Mesh(blade, mat(0x2a2a2a));
        b.rotation.z = rz;
        spinner.add(b);
      }
      g.add(spinner);
      break;
    }
    case 'jet': {
      g.add(new THREE.Mesh(geo('jetBody', () => zCyl(S * 0.4, S * 0.48, S)), mat(d.color)));
      const glow = new THREE.Mesh(geo('jetGlow', () => zCyl(S * 0.32, S * 0.32, S * 0.08)), mat(0xff9a3c, true));
      glow.position.z = S * 0.52;        // nozzle at the back (+z)
      g.add(glow);
      const intake = new THREE.Mesh(geo('jetIntake', () => zCyl(S * 0.3, S * 0.3, S * 0.06)), mat(0x1a1f28, true));
      intake.position.z = -S * 0.51;
      g.add(intake);
      break;
    }
    case 'cannon': {
      g.add(new THREE.Mesh(geo('gunBase', () => new THREE.BoxGeometry(S * 0.55, S * 0.55, S * 0.7)), mat(d.color)));
      const barrel = new THREE.Mesh(geo('barrel', () => zCyl(S * 0.09, S * 0.12, S * 1.3, 8)), mat(0x22252c));
      barrel.position.z = -S * 0.8;
      g.add(barrel);
      break;
    }
    case 'pylon': {
      // the pylon body itself is generated by struts.js (connected to whatever it hangs from); only the missiles are drawn here
      const body = new THREE.Mesh(geo('mslBody', () => zCyl(S * 0.16, S * 0.16, S * 1.05, 10)), mat(d.color));
      g.add(body);
      const tip = new THREE.Mesh(geo('mslTip', () => {
        const c = new THREE.ConeGeometry(S * 0.16, S * 0.32, 10);
        c.rotateX(-Math.PI / 2);
        return c;
      }), mat(0xff6a5a));
      tip.position.z = -S * 0.68;
      g.add(tip);
      break;
    }
  }
  return { group: g, spinner };
}

const STRUT_COLOR = { pylon: 0x6b7280, strut: 0x55606e, biplane: 0x8a6a4a };

/* The whole plane: parts placed at their cell coordinates + auto-struts. Returns { group, propellers, struts } */
export function buildBlueprintMesh(parts) {
  const root = new THREE.Group();
  const propellers = [];
  const byCell = new Map();
  for (const p of parts) {
    const { group, spinner } = buildPart(p.type);
    group.position.set(p.x * CELL, p.y * CELL, p.z * CELL);
    group.userData.cell = { x: p.x, y: p.y, z: p.z };
    root.add(group);
    byCell.set(cellKey(p.x, p.y, p.z), group);
    if (spinner) propellers.push(spinner);
  }

  // auto-struts: connect floating parts to the neighbor they hang from (see struts.js)
  const struts = computeStruts(parts);
  for (const st of struts) {
    const owner = byCell.get(cellKey(st.owner.x, st.owner.y, st.owner.z));
    if (!owner) continue;
    const [sx, sy, sz] = st.size;
    const m = new THREE.Mesh(
      geo(`strut:${sx.toFixed(2)},${sy.toFixed(2)},${sz.toFixed(2)}`, () => new THREE.BoxGeometry(sx, sy, sz)),
      mat(STRUT_COLOR[st.kind]));
    m.position.set(st.local[0], st.local[1], st.local[2]);
    owner.add(m);
  }
  return { group: root, propellers, struts };
}
